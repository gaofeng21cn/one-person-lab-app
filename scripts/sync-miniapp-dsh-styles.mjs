import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Vanilla MCP Apps cannot mount React primitives. Keep the official declaration
// values and adapt only CSS Module selectors to their existing HTML controls.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const argument = name => { const i = args.indexOf(name); return i < 0 ? undefined : args[i + 1]; };
const source = argument('--source');
assert.ok(source, 'Provide a clean official DSH checkout with --source');
const cohort = JSON.parse(await readFile(path.join(root, 'contracts/app-gui-visual-source-cohort.json'), 'utf8'));
const ref = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
assert.equal(ref, cohort.upstream.commit, 'DSH source must match the App visual source cohort');
assert.equal(execFileSync('git', ['-C', source, 'status', '--porcelain'], { encoding: 'utf8' }).trim(), '', 'DSH source must be clean');
const read = relative => readFile(path.join(source, 'packages/client', relative), 'utf8');
const names = ['base.css', 'design-platform.css', 'gradient-shadow-text.css', 'focus.css', 'scrollbar.css'];
const theme = await Promise.all(names.map(name => read(`ui-theme/src/styles/${name}`)));
const selectors = {
  button: '.dsh-button', md: '.dsh-button:not(.small)', sm: '.dsh-button.small',
  primary: '.dsh-button.primary', ghost: '.dsh-button.quiet',
  outline: '.dsh-button:not(.primary):not(.quiet)', toolbar: '.dsh-button.toolbar', icon: '.dsh-button-icon'
};
const button = (await read('ui-primitives/src/Button.module.css'))
  .replace(/\.(button|md|sm|primary|ghost|outline|toolbar|icon)\b/g, (_, name) => selectors[name]);
const input = await read('ui-primitives/src/Input.module.css');
const declaration = selector => {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = input.match(new RegExp(escaped + '\\s*\\{([^}]+)\\}'));
  assert.ok(match, `Missing official Input rule ${selector}`);
  return match[1];
};
// Input.tsx separates a frame and inner input. Native select/textarea controls
// use the same frame declarations and inner typography on one element.
const field = `.dsh-input {${declaration('.wrap')}${declaration('.input').split(';').filter(value => /^\s*(font-size|line-height|color|outline):/.test(value)).join(';')};}\n`
  + `.dsh-input:focus {${declaration('.wrap:focus-within')}}\n`
  + `.dsh-input::placeholder {${declaration('.input::placeholder')}}\n`;
const css = `/* Generated by one-person-lab-app/scripts/sync-miniapp-dsh-styles.mjs.
 * Official DSH ${ref}; MIT license in DSH-LICENSE.txt.
 * Theme declarations are unchanged. Button/Input selectors adapt CSS Modules to HTML.
 */\n${theme.join('\n')}\n${button}\n${field}
body {
  --dsw-font-family: var(--font-sans, var(--dsh-font-family-text-default));
  --ds-font-family-code: var(--font-mono, var(--dsh-font-family-code-default));
  font: var(--dsw-font-s-14);
  color: var(--dsw-alias-label-primary);
}
button, input, select, textarea { font-family: inherit; }
h1 { font: var(--dsw-font-l-20); }
h2 { font: var(--dsw-font-base-strong-16); }
h3 { font: var(--dsw-font-s-strong-14); }
`;
const license = await readFile(path.join(source, 'LICENSE'), 'utf8');
const targets = [path.join(root, 'resources/miniapp-dsh')];
for (const [flag, relative] of [
  ['--framework-root', 'src/mcp-app'], ['--relay-root', 'workbench'],
  ['--mac-root', 'plugins/med-autocast/media-review']
]) { const repo = argument(flag); if (repo) targets.push(path.resolve(repo, relative)); }
for (const target of targets) {
  if (!args.includes('--check')) await mkdir(target, { recursive: true });
  for (const [name, content] of [['dsh-theme.css', css], ['DSH-LICENSE.txt', license]]) {
    if (args.includes('--check')) assert.equal(await readFile(path.join(target, name), 'utf8'), content, `DSH styles drifted: ${target}/${name}`);
    else await writeFile(path.join(target, name), content);
  }
}
console.log(JSON.stringify({ source: ref, targets, status: args.includes('--check') ? 'consistent' : 'synchronized' }));
